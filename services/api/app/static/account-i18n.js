  const text = value => !value ? '' : window.NutriI18n.getLanguage() === 'en'
    ? (strings[value] ?? window.NutriI18n.systemText(value)) : value;
  const nodes = [], attributes = [], notices = new Map();
  function translateNotice(value,sourceLanguage){
    if(sourceLanguage===window.NutriI18n.getLanguage())return value;
    const pairs=Object.entries(strings).map(([zh,en])=>sourceLanguage==='en'?[en,zh]:[zh,en]).filter(([from])=>from.length>=4).sort((a,b)=>b[0].length-a[0].length);
    const escaped=parts=>parts.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
    const lookup=new Map(pairs);
    return value.replace(new RegExp(pairs.map(([from])=>escaped(from)).join('|'),'g'),match=>lookup.get(match));
  }
  function message(id,value,error=false){
    notices.set(id,{value,language:window.NutriI18n.getLanguage()});
    const node=document.getElementById(id);node.textContent=value;node.classList.toggle('error',error);
  }
  let captured = false;
  function capture() {
    if (captured) return;
    captured = true;
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while(walker.nextNode()) {
      const node=walker.currentNode, parent=node.parentElement;
      if(parent.closest('script,style,[data-i18n]'))continue;
      const original=node.textContent.trim();
      if(Object.hasOwn(strings,original))nodes.push({node,original});
    }
    document.querySelectorAll('[placeholder],[aria-label]').forEach(node=>{
      for(const attr of ['placeholder','aria-label']){
        const original=node.getAttribute(attr);
        if(Object.hasOwn(strings,original))attributes.push({node,attr,original});
      }
    });
  }
  function apply(){
    capture();
    for(const [id,{value,language}] of notices)document.getElementById(id).textContent=translateNotice(value,language);
    for(const {node,original} of nodes)if(node.isConnected)node.textContent=text(original);
    for(const {node,attr,original} of attributes)if(node.isConnected)node.setAttribute(attr,text(original));
  }
  window.NutriAccountI18n={text,apply,message};
